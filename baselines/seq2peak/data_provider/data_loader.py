class Dataset_STSEP_Seq2Peak(Dataset):
    """
    Seq2Peak-compatible STSEP dataset loader with fixed split indices.
    """
    def __init__(self, root_path, flag='train', size=None,
                 features='S', data_path='wlel.csv',
                 target='OT', scale=True, timeenc=0, freq='h',
                 train_only=False, args=None):
        if size is None:
            self.seq_len = 96
            self.label_len = 48
            self.pred_len = 96
        else:
            self.seq_len = size[0]
            self.label_len = size[1]
            self.pred_len = size[2]

        assert flag in ['train', 'test', 'val']
        self.flag = flag
        self.features = features
        self.target = target
        self.scale = scale
        self.timeenc = timeenc
        self.freq = freq
        self.root_path = root_path
        self.data_path = data_path

        self.dataset_config = getattr(args, 'dataset_config', '') if args is not None else ''
        self.dataset_name = (
            getattr(args, 'dataset_name', '') if args is not None else ''
        ) or os.path.splitext(os.path.basename(self.data_path))[0]
        self.window_stride = max(1, int(getattr(args, 'window_stride', 1))) if args is not None else 1

        self.__read_data__()

    def __read_data__(self):
        if not self.dataset_config:
            raise ValueError('--dataset_config is required when --data stsep')
        self.scaler = StandardScaler()

        ds_cfg, splits = _read_stsep_split(self.dataset_config, self.dataset_name, self.flag)
        split_cfg = splits[self.flag]
        train_cfg = splits['train']
        border1 = int(split_cfg['start'])
        border2 = int(split_cfg['end']) + 1
        train_b1 = int(train_cfg['start'])
        train_b2 = int(train_cfg['end']) + 1

        csv_path = os.path.join(self.root_path, self.data_path)
        df_raw = pd.read_csv(csv_path)
        if 'date' not in df_raw.columns and 'timestamp' in df_raw.columns:
            df_raw = df_raw.rename(columns={'timestamp': 'date'})
        if 'date' not in df_raw.columns:
            raise KeyError(f'Expected `date` column in {csv_path}')
        if self.target not in df_raw.columns:
            raise KeyError(f'Expected target column `{self.target}` in {csv_path}')

        if self.features in ['M', 'MS']:
            cols_data = [c for c in df_raw.columns if c != 'date']
            df_data = df_raw[cols_data]
        else:
            df_data = df_raw[[self.target]]

        if self.scale:
            train_data = df_data.iloc[train_b1:train_b2]
            self.scaler.fit(train_data.values)
            data = self.scaler.transform(df_data.values)
        else:
            data = df_data.values

        df_stamp = df_raw[['date']].iloc[border1:border2].copy()
        df_stamp['date'] = pd.to_datetime(df_stamp['date'])
        if self.timeenc == 0:
            df_stamp['month'] = df_stamp.date.apply(lambda row: row.month, 1)
            df_stamp['day'] = df_stamp.date.apply(lambda row: row.day, 1)
            df_stamp['weekday'] = df_stamp.date.apply(lambda row: row.weekday(), 1)
            df_stamp['hour'] = df_stamp.date.apply(lambda row: row.hour, 1)
            data_stamp = df_stamp.drop(['date'], axis=1).values
        else:
            data_stamp = time_features(pd.to_datetime(df_stamp['date'].values), freq=self.freq)
            data_stamp = data_stamp.transpose(1, 0)

        self.border1 = border1
        self.border2 = border2
        self.data_x = data[border1:border2]
        self.data_y = data[border1:border2]
        self.data_stamp = data_stamp

        max_start = border2 - self.seq_len - self.pred_len
        if max_start < border1:
            self.starts_global = np.array([], dtype=np.int64)
            self.starts_local = np.array([], dtype=np.int64)
        else:
            offset = (self.window_stride - (border1 % self.window_stride)) % self.window_stride
            first_aligned = border1 + offset
            self.starts_global = np.arange(
                first_aligned, max_start + 1, self.window_stride, dtype=np.int64
            )
            self.starts_local = self.starts_global - border1

    def __getitem__(self, index):
        s_begin = int(self.starts_local[index])
        s_end = s_begin + self.seq_len
        r_begin = s_end - self.label_len
        r_end = r_begin + self.label_len + self.pred_len

        seq_x = self.data_x[s_begin:s_end]
        seq_y = self.data_y[r_begin:r_end]
        seq_x_mark = self.data_stamp[s_begin:s_end]
        seq_y_mark = self.data_stamp[r_begin:r_end]
        return seq_x, seq_y, seq_x_mark, seq_y_mark

    def __len__(self):
        return len(self.starts_local)

    def inverse_transform(self, data):
        return self.scaler.inverse_transform(data)


